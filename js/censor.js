// ==========================================
// ★ 文字正規化
//
// 例如：
// "F U C K"  → "fuck"
// "F.U.C.K"  → "fuck"
// "ＦＵＣＫ" → "fuck"
// "幹-你-娘" → "幹你娘"
// ==========================================
function normalizeText(text) {
  if (!text) return "";

  return (
    String(text)
      // Unicode 相容正規化
      .normalize("NFKC")

      // 英文統一小寫
      .toLowerCase()

      // 移除零寬字元 / 不可見字元
      .replace(/[\u200B-\u200D\u2060\uFEFF]/g, "")

      // 移除所有 Unicode 空白
      .replace(/\s+/gu, "")

      // 移除 Unicode 標點與特殊符號
      .replace(/[\p{P}\p{S}]/gu, "")
  );
}

// ==========================================
// ★ 英文 Leetspeak 正規化
//
// 常見：
// 0 → o
// 1 → i
// 3 → e
// 4 → a
// 5 → s
// 7 → t
// @ → a
// $ → s
//
// 例如：
// sh1t → shit
// b1tch → bitch
// ==========================================
function normalizeLeet(text) {
  return text.replace(/[013457@$]/g, (char) => {
    const map = {
      "0": "o",
      "1": "i",
      "3": "e",
      "4": "a",
      "5": "s",
      "7": "t",
      "@": "a",
      "$": "s",
    };

    return map[char] || char;
  });
}

// ==========================================
// ★ 預先建立正規化字典
//
// 遊戲運行期間只建立一次，
// 不需要每次玩家輸入都重新處理。
// ==========================================
const NORMALIZED_PROFANITY_LIST = PROFANITY_LIST.map((word) =>
  normalizeText(word),
).filter(Boolean);

// ==========================================
// ★ 唯一公開函式
//
// 外部只需要：
//
// import { containsProfanity } from "./profanityFilter.js";
//
// if (containsProfanity(name)) {
//   ...
// }
//
// 不需要修改任何原本的呼叫方式。
// ==========================================
export function containsProfanity(text) {
  if (!text) return false;

  // ------------------------------------------
  // 第一層：一般正規化
  // ------------------------------------------
  const cleanText = normalizeText(text);

  if (!cleanText) return false;

  if (NORMALIZED_PROFANITY_LIST.some((word) => cleanText.includes(word))) {
    return true;
  }

  // ------------------------------------------
  // 第二層：英文 Leetspeak
  // ------------------------------------------
  const leetText = normalizeLeet(cleanText);

  if (leetText !== cleanText) {
    if (NORMALIZED_PROFANITY_LIST.some((word) => leetText.includes(word))) {
      return true;
    }
  }

  // ------------------------------------------
  // 沒有偵測到
  // ------------------------------------------
  return false;
}
